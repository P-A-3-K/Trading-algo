"""MQL5 Expert Advisor: the ORB trader as an MT5 robot that can run on MetaQuotes' hosting (VPS).

    python -m quantlab.mql5 calendar        # (re)writes mql5/QuantLabCalendar.mqh (holidays 2024-2030)
    python -m quantlab.mql5 install         # copies the EA into your MT5 and compiles it

The EA (mql5/QuantLabORB.mq5) follows the same rules as quantlab/live.py. MT5 can't know
exchange holidays, so QuantLab writes them into QuantLabCalendar.mqh from the same exchange
calendars the Python trader uses (closed days, and early closes with their closing time).
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "mql5"
EXCHANGES = {"US": "XNYS", "EU": "XETR", "UK": "XLON", "JP": "XJPX"}
LOCAL = {"US": "America/New_York", "EU": "Europe/Berlin", "UK": "Europe/London", "JP": "Asia/Tokyo"}
NORMAL_CLOSE = {"US": 16 * 60, "EU": 17 * 60 + 30, "UK": 16 * 60 + 30, "JP": 15 * 60}


def calendar_mqh(first: int = 2024, last: int = 2030) -> str:
    """MQL5 include with closed weekdays and early closes per exchange, as yyyymmdd numbers."""
    import pandas as pd
    import pandas_market_calendars as pmc
    lines = ["// Generated by: python -m quantlab.mql5 calendar   (do not edit by hand)",
             f"// Exchange holidays and early closes {first}-{last}: closed weekdays, early-close days + close minute",
             ""]
    for key, code in EXCHANGES.items():
        cal = pmc.get_calendar(code)
        sched = cal.schedule(f"{first}-01-01", f"{last}-12-31")
        weekdays = pd.bdate_range(f"{first}-01-01", f"{last}-12-31")
        open_days = set(sched.index.date)
        closed = [int(d.strftime("%Y%m%d")) for d in weekdays if d.date() not in open_days]
        early, early_min = [], []
        for d, row in sched.iterrows():
            close = row["market_close"].tz_convert(LOCAL[key])
            m = close.hour * 60 + close.minute
            if m < NORMAL_CLOSE[key]:
                early.append(int(d.strftime("%Y%m%d")))
                early_min.append(m)
        fmt = lambda xs: ", ".join(str(x) for x in xs) or "0"
        lines += [f"int QL_{key}_CLOSED[] = {{{fmt(closed)}}};",
                  f"int QL_{key}_EARLY[] = {{{fmt(early)}}};",
                  f"int QL_{key}_EARLY_MIN[] = {{{fmt(early_min)}}};", ""]
    return "\n".join(lines)


def write_calendar(path: Path = SRC / "QuantLabCalendar.mqh") -> Path:
    path.write_text(calendar_mqh(), encoding="utf-8")
    return path


def install(path_hint: str = None):
    """Copy the EA + calendar into MT5's data folder (MQL5/Experts/QuantLab) and compile it."""
    from . import mt5 as M
    mt5, info = M.connect(path_hint)
    term = mt5.terminal_info()
    data = Path(term.data_path)
    dest = data / "MQL5" / "Experts" / "QuantLab"
    dest.mkdir(parents=True, exist_ok=True)
    for f in ("QuantLabORB.mq5", "QuantLabCalendar.mqh"):
        shutil.copy2(SRC / f, dest / f)
    print(f"  Copied the EA to {dest}  ({info['company']} · {info['server']})")
    editor = Path(term.path) / "metaeditor64.exe"
    if not editor.exists():
        print(f"  MetaEditor not found next to the terminal; open {dest / 'QuantLabORB.mq5'} in MetaEditor and press F7.")
        return
    log = dest / "compile.log"
    subprocess.run([str(editor), f"/compile:{dest / 'QuantLabORB.mq5'}", f"/log:{log}"], check=False)
    text = log.read_bytes().decode("utf-16", errors="ignore") if log.exists() else ""
    if not text:
        print("  Compiled (no log written). In MT5: Navigator > Expert Advisors > QuantLab > QuantLabORB.")
        return
    errors = [l for l in text.splitlines() if " error " in l.lower() or ": error" in l.lower()]
    result = [l for l in text.splitlines() if "result" in l.lower()]
    for l in (errors[:30] or []) + result[-1:]:
        print("  " + l.strip())
    if not errors:
        print("  Compiled OK. In MT5: Navigator > Expert Advisors > QuantLab > QuantLabORB (right-click > Refresh if not shown).")


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    cmd = args[0] if args else ""
    if cmd == "calendar":
        print(f"  Wrote {write_calendar()}")
    elif cmd == "install":
        path = args[args.index("--path") + 1] if "--path" in args else None
        try:
            install(path)
        except Exception as e:
            print(f"  {e}")
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
